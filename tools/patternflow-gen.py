# Builds vendor/patternflow-patterns.js for the studio from Patternflow's own JS pattern sources (read as data, never run here).
import re, glob, json, sys, os
SRC = sys.argv[1]; OUT = sys.argv[2]
pats = []
for f in sorted(glob.glob(os.path.join(SRC, 'pattern-*.ts'))):
    s = open(f, encoding='utf-8').read()
    if 'labOnly: true' in s: continue                      # these need Pattern Lab's colour ramp
    m = re.search(r'code: `(.*)`,?\s*\n\};?\s*$', s, re.S)
    if not m: continue
    code = m.group(1)
    if '\\' in code or '${' in code or '`' in code: print('skip (escapes)', f); continue
    if 'setValue' in code: continue
    g = lambda k, d='': (re.search(r'\b%s: "([^"]*)"' % k, s) or [None, d])[1]
    num = int((re.search(r'\bnum: (\d+)', s) or [0, '0'])[1])
    kn = re.search(r'^[ \t]*//[ \t]*@knobs[ \t]+(.+)$', code, re.M); knobs = None
    if kn:
        knobs = [None] * 4
        for i, part in enumerate(kn.group(1).split(',')[:4]):
            mm = re.match(r'^(.+?)\s*=\s*(-?\d*\.?\d+)\s*\.\.\s*(-?\d*\.?\d+)$', part.strip())
            if mm and float(mm.group(3)) > float(mm.group(2)): knobs[i] = [mm.group(1).strip()[:14], float(mm.group(2)), float(mm.group(3))]
    code = re.sub(r'^export\s+', '', code, flags=re.M)
    pats.append(dict(id=g('id'), num=num, name=g('name'), desc=g('desc'), author=g('author', 'Seunghun LEE'), license=g('license', 'CC-BY-SA-4.0'), knobs=knobs, code=code))
pats.sort(key=lambda p: p['num'])
out = ["""/* Patterns from Patternflow, the open-source LED synthesizer by Seunghun Lee (@engmung) and contributors.
   https://github.com/engmung/Patternflow · https://patternflow.work
   Each pattern below is its author's work under CC BY-SA 4.0 (see vendor/PATTERNFLOW-NOTICE.md); the source text of every
   pattern is unchanged apart from dropping the "export" keyword so it can sit inside a function here.
   Generated by tools/patternflow-gen.py. Do not edit by hand. */
var PFPATS = ["""]
for p in pats:
    meta = {k: p[k] for k in ('id', 'name', 'desc', 'author', 'license', 'knobs')}
    out.append('{ meta:' + json.dumps(meta, ensure_ascii=False) + ', make:function(){\n' + p['code'] + '\nreturn { setup:setup, update:update, draw:draw };\n} },')
out.append('];\n')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out)); print(len(pats), 'patterns', os.path.getsize(OUT), 'bytes')
